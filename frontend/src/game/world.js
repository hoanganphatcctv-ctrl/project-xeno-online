  pointHitsClosedDoor(x, y) {
    for (let i = 0; i < this.doors.length; i++) {
      const d = this.doors[i];
      if (d.openAmount >= 0.75) continue; // Door is open enough to pass

      // Closed leaf boxes
      const retract = d.openAmount * 0.85;
      if (d.orient === "vertical") {
        const halfH = d.h * 0.5;
        const leafH = halfH * (1 - retract);
        if (x >= d.x && x <= d.x + d.w) {
          if (y >= d.y && y <= d.y + leafH) return true;
          if (y >= d.y + d.h - leafH && y <= d.y + d.h) return true;
        }
      } else {
        const halfW = d.w * 0.5;
        const leafW = halfW * (1 - retract);
        if (y >= d.y && y <= d.y + d.h) {
          if (x >= d.x && x <= d.x + leafW) return true;
          if (x >= d.x + d.w - leafW && x <= d.x + d.w) return true;
        }
      }
    }
    return false;
  }

  pointHitsWall(x, y) {
    for (let i = 0; i < this.walls.length; i++) {
      const w = this.walls[i];
      if (x >= w.x && x <= w.x + w.w && y >= w.y && y <= w.y + w.h) {
        return true;
      }
    }
    return this.pointHitsClosedDoor(x, y);
  }

  resolveSliding(entity) {
    const rad = entity.radius || 16;

    // Check world bounds
    entity.x = Math.max(rad + this.BORDER_T, Math.min(this.WORLD_W - rad - this.BORDER_T, entity.x));
    entity.y = Math.max(rad + this.BORDER_T, Math.min(this.WORLD_H - rad - this.BORDER_T, entity.y));

    // Walls sliding resolution
    for (let i = 0; i < this.walls.length; i++) {
      const w = this.walls[i];
      const nearestX = Math.max(w.x, Math.min(entity.x, w.x + w.w));
      const nearestY = Math.max(w.y, Math.min(entity.y, w.y + w.h));
      const dx = entity.x - nearestX;
      const dy = entity.y - nearestY;
      const dist = Math.hypot(dx, dy);

      if (dist < rad) {
        const overlap = rad - dist;
        const pushX = dist > 0 ? (dx / dist) * overlap : 1;
        const pushY = dist > 0 ? (dy / dist) * overlap : 0;
        entity.x += pushX;
        entity.y += pushY;
      }
    }

    // Closed doors sliding resolution (Only when door is firmly closed < 0.20)
    for (let i = 0; i < this.doors.length; i++) {
      const d = this.doors[i];
      if (d.openAmount >= 0.20) continue;

      const nearestX = Math.max(d.x, Math.min(entity.x, d.x + d.w));
      const nearestY = Math.max(d.y, Math.min(entity.y, d.y + d.h));
      const dx = entity.x - nearestX;
      const dy = entity.y - nearestY;
      const dist = Math.hypot(dx, dy);

      if (dist < rad && dist > 0.001) {
        const overlap = rad - dist;
        entity.x += (dx / dist) * overlap;
        entity.y += (dy / dist) * overlap;
      }
    }

    // Props sliding resolution (Supercomputers, Desks, Particle Accelerators)
    const obstacleProps = [...this.spaceProps, ...this.computerDesks];
    for (let i = 0; i < obstacleProps.length; i++) {
      const p = obstacleProps[i];
      const nearestX = Math.max(p.x, Math.min(entity.x, p.x + p.w));
      const nearestY = Math.max(p.y, Math.min(entity.y, p.y + p.h));
      const dx = entity.x - nearestX;
      const dy = entity.y - nearestY;
      const dist = Math.hypot(dx, dy);
      if (dist < rad && dist > 0.001) {
        const overlap = rad - dist;
        entity.x += (dx / dist) * overlap;
        entity.y += (dy / dist) * overlap;
      }
    }

    // Nuclear Vats sliding resolution
    for (let i = 0; i < this.nuclearVats.length; i++) {
      const v = this.nuclearVats[i];
      if (!v.active) continue;
      const dx = entity.x - v.x;
      const dy = entity.y - v.y;
      const dist = Math.hypot(dx, dy);
      const minD = rad + v.radius;
      if (dist < minD && dist > 0.001) {
        const overlap = minD - dist;
        entity.x += (dx / dist) * overlap;
        entity.y += (dy / dist) * overlap;
      }
    }
  }

