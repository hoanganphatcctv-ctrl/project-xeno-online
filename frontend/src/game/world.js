  explodeBarrel(b, engine) {
    if (!b.active) return;
    b.active = false;

    // Queue for coop network sync if engine is tracking
    if (engine && Array.isArray(engine.pendingExplodedBarrels) && b.id !== undefined) {
      if (!engine.pendingExplodedBarrels.includes(b.id)) {
        engine.pendingExplodedBarrels.push(b.id);
      }
    }

    if (engine && typeof engine.bakeScorchCrater === "function") {
      engine.bakeScorchCrater(b.x, b.y, 85, b.type === "acid");
    }

    if (engine && typeof engine.spawnShockwave === "function") {
      engine.spawnShockwave(b.x, b.y, b.type === "acid" ? "#4ade80" : "#f97316", 185);
    }
    if (engine && typeof engine.spawnFirePatch === "function" && b.type !== "acid") {
      engine.spawnFirePatch(b.x, b.y, 65, 240, true);
    }

    if (engine.sfx) engine.sfx.playExplosion(true);
    engine.screenShake = 22;

    // Damage nearby entities (Enemies, Bosses, Player)
    const blastRadius = 160;

    // Damage enemies
    for (let i = 0; i < engine.MAX_ENEMIES; i++) {
      const e = engine.enemies[i];
      if (!e.active) continue;
      const d = Math.hypot(e.x - b.x, e.y - b.y);
      if (d <= blastRadius) {
        const falloff = 1 - d / blastRadius;
        engine.damageEnemy(e, 220 * falloff, (e.x - b.x) * 0.1, (e.y - b.y) * 0.1, b.type === "acid" ? "acid" : "flame");
      }
    }

    // Damage bosses
    engine.bosses.forEach(boss => {
      if (boss.active && boss.hp > 0) {
        const d = Math.hypot(boss.x - b.x, boss.y - b.y);
        if (d <= blastRadius + boss.radius) {
          engine.damageBoss(boss, 320, "flame");
        }
      }
    });

    // Damage player if caught in blast
    const pd = Math.hypot(engine.player.x - b.x, engine.player.y - b.y);
    if (pd <= blastRadius) {
      engine.damagePlayer(Math.round(45 * (1 - pd / blastRadius)));
    }

    // Create persistent acid pool if bio-acid
    if (b.type === "acid") {
      this.acidPools.push({
        x: b.x,
        y: b.y,
        radius: 110,
        life: 10 * 60 // 10 seconds
      });
    }

    // Spawn Fiery Particles
    for (let s = 0; s < 25; s++) {
      const ang = Math.random() * Math.PI * 2;
      const spd = 2 + Math.random() * 8;
      engine.spawnParticle(
        b.x,
        b.y,
        Math.cos(ang) * spd,
        Math.sin(ang) * spd,
        b.type === "acid" ? "#4ade80" : "#f97316",
        3.5,
        25
      );
    }
  }

