export function cloneWeaponData() {
  return WEAPON_DEFINITIONS.map(w => ({ ...w }));
}

export function syncWeaponsMaxAmmo(weapons, dmgLevel = 1, bonusPerUpgrade = 30) {
  const bonus = Math.max(0, (dmgLevel - 1) * bonusPerUpgrade);
  weapons.forEach(w => {
    if (w.baseMaxAmmo !== Infinity) {
      w.maxAmmo = w.baseMaxAmmo + bonus;
      w.ammo = Math.min(w.maxAmmo, w.ammo);
    }
  });
}

